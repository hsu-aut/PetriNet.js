/**
 * Bundles src/search/worker.js into src/search/workerSource.js, a module that
 * exports the worker as a string. The package ships its sources and every host
 * bundles them its own way, so a separate worker file would need a copy step in
 * each of them. A string needs none: the page starts the worker from a Blob.
 *
 *   npm run build:worker            writes the file
 *   node scripts/build-worker.mjs --check   fails if the committed file is stale
 */
import * as esbuild from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'src/search/workerSource.js');

export async function built() {
  const result = await esbuild.build({
    entryPoints: [resolve(root, 'src/search/worker.js')],
    bundle: true,
    format: 'iife',
    target: 'es2022',
    // Not minified: a stack trace from the worker should be readable.
    minify: false,
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });

  const source = result.outputFiles[0].text;
  return [
    '// Generated by scripts/build-worker.mjs from worker.js. Do not edit; run `npm run build:worker`.',
    `export default ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fresh = await built();
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current.replace(/\r\n/g, '\n') !== fresh) {
      console.error('src/search/workerSource.js is out of date; run `npm run build:worker`.');
      process.exit(1);
    }
    console.log('workerSource.js is up to date');
  } else {
    await writeFile(target, fresh);
    console.log(`wrote ${target}`);
  }
}
